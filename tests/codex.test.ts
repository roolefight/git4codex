import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { CallToolResultSchema, ListRootsRequestSchema } from '@modelcontextprotocol/sdk/types.js';
import { App } from '@modelcontextprotocol/ext-apps';
import { AppBridge, getToolUiResourceUri } from '@modelcontextprotocol/ext-apps/app-bridge';
import { pathToFileURL } from 'node:url';
import { git } from '../src/core/git';
import type { DiffResult, RepoState, WorktreeState } from '../src/shared/protocol';
import type { PanelData } from '../src/codex/protocol';
import { createGitTransport } from '../src/codex/bridge';
test('MCP client launches shared service and completes status, stage and commit', async t => {
  const base = path.resolve('.test-repos'); await mkdir(base, { recursive: true });
  const root = await mkdtemp(path.join(base, 'mcp-'));
  const runtime = path.join(root, 'state');
  const repository = path.join(root, 'repo'); await mkdir(repository);
  const codexHome = path.join(root, 'codex-home'); await mkdir(codexHome);
  const threadId = '11111111-1111-4111-8111-111111111111';
  const metadata = new DatabaseSync(path.join(codexHome, 'state_5.sqlite'));
  metadata.exec('CREATE TABLE threads (id TEXT PRIMARY KEY, cwd TEXT NOT NULL)');
  metadata.prepare('INSERT INTO threads VALUES (?, ?)').run(threadId, repository);
  metadata.close();
  const client = new Client({ name: 'workbench-test', version: '1' }, { capabilities: { roots: {} } });
  client.setRequestHandler(ListRootsRequestSchema, () => ({ roots: [{ uri: pathToFileURL(repository).href, name: 'Current chat workspace' }] }));
  const env = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => typeof entry[1] === 'string'));
  t.after(async () => {
    await client.close();
    const info = await readFile(path.join(runtime, 'connection.json'), 'utf8').then(JSON.parse).catch(() => undefined);
    if (info?.pid && info.url === 'http://127.0.0.1:47839') { try { process.kill(info.pid); } catch {} }
    if (!root.startsWith(base + path.sep)) throw new Error('Unsafe test cleanup');
    await new Promise(resolve => setTimeout(resolve, 200));
    await rm(root, { recursive: true, force: true });
  });
  await git(repository, ['init', '-b', 'main']);
  await git(repository, ['config', 'user.name', 'MCP Test']);
  await git(repository, ['config', 'user.email', 'mcp@example.invalid']);
  await writeFile(path.join(repository, 'hello.txt'), 'hello from MCP\n');
  const entry = path.resolve(process.env.GIT_WORKBENCH_MCP_ENTRY ?? 'dist/mcp.cjs');
  await client.connect(new StdioClientTransport({ command: process.execPath, args: [entry], cwd: path.dirname(entry), env: { ...env, CODEX_HOME: codexHome, GIT_WORKBENCH_HOME: runtime, GIT_WORKBENCH_PORT: '47839' }, stderr: 'pipe' }));
  const tools = await client.listTools();
  const panelTool = tools.tools.find(tool => tool.name === 'git_workbench_panel');
  assert.ok(panelTool);
  assert.deepEqual(panelTool._meta?.['openai/ui'], { entrypoints: [{ type: 'thread' }] });
  const uri = getToolUiResourceUri(panelTool)!;
  assert.equal(uri, 'ui://git-workbench/panel.html');
  const resources = await client.listResources();
  assert.ok(resources.resources.some(resource => resource.uri === uri));
  const resource = (await client.readResource({ uri })).contents[0];
  assert.equal(resource.mimeType, 'text/html;profile=mcp-app');
  assert.deepEqual(resource._meta?.['openai/ui'], { availableDisplayModes: ['inline', 'fullscreen'], preferredDisplayMode: 'fullscreen' });
  assert.deepEqual(resource._meta?.ui, { prefersBorder: false, csp: { connectDomains: [], resourceDomains: [] } });
  assert.ok('text' in resource);
  assert.match(resource.text, /<div id="root"><\/div>/);
  assert.doesNotMatch(resource.text, /<script[^>]+src=|<link[^>]+href=/, 'Panel must be self-contained');
  const picker = await client.callTool({ name: 'git_workbench_panel', arguments: {} });
  const pickerData = picker.structuredContent as unknown as PanelData;
  assert.equal(pickerData.phase, 'pending', 'The app shell arrives before repository discovery');
  assert.equal(pickerData.source, 'mcp-roots');
  assert.equal(pickerData.repositories.length, 0);
  assert.deepEqual(pickerData.roots, [{ name: 'Current chat workspace', path: repository }]);
  const native = await client.callTool({ name: 'git_workbench_panel', arguments: {}, _meta: { thread_id: threadId, threadId } });
  const nativeData = native.structuredContent as unknown as PanelData;
  assert.equal(nativeData.source, 'codex-thread');
  assert.equal(nativeData.roots[0]?.path, repository, 'Empty native sidebar calls must resolve the thread cwd even when process cwd is the plugin directory');
  const loaded = (await client.callTool({ name: 'git_workbench_workspace', arguments: {}, _meta: { thread_id: threadId, threadId } })).structuredContent as unknown as PanelData;
  assert.equal(loaded.state?.root, repository);
  assert.ok(tools.tools.some(tool => tool.name === 'git_workbench_stage'));
  assert.ok(!tools.tools.find(tool => tool.name === 'git_workbench_stage')?.inputSchema.properties?.action);
  const unopened = await client.callTool({ name: 'git_workbench_status', arguments: { repo: 'other-chat-repo' } });
  assert.equal(unopened.isError, true);
  const open = await client.callTool({ name: 'git_workbench_open', arguments: { path: repository } });
  assert.ok(!open.isError, JSON.stringify(open));
  const contents = open.content as { type: string; text: string }[];
  const opened: { state: RepoState; url?: string } = JSON.parse(contents[0].text);
  assert.equal(opened.url, undefined, 'Codex plugin must return state, not send users to a browser');
  // Official UI protocol: App → AppBridge → real stdio MCP → real Git.
  const app = new App({ name: 'panel-test', version: '1' }, {}, { autoResize: false });
  const host = new AppBridge(client, { name: 'test-host', version: '1' }, { serverTools: {} }, { hostContext: { theme: 'dark', displayMode: 'fullscreen' } });
  const [viewTransport, hostTransport] = InMemoryTransport.createLinkedPair();
  t.after(async () => { await app.close(); await host.close(); });
  const received = new Promise<PanelData>(resolve => { app.ontoolresult = result => resolve(result.structuredContent as unknown as PanelData); });
  await host.connect(hostTransport);
  await app.connect(viewTransport);
  const panel = await client.callTool({ name: 'git_workbench_panel', arguments: { path: repository } });
  await host.sendToolInput({ arguments: { path: repository } });
  await host.sendToolResult(CallToolResultSchema.parse(panel));
  assert.equal((await received).phase, 'pending');
  const viewWorkspace = await app.callServerTool({ name: 'git_workbench_workspace', arguments: { path: repository } });
  assert.equal((viewWorkspace.structuredContent as unknown as PanelData).state?.repo, opened.state.repo);
  assert.equal(app.getHostContext()?.theme, 'dark');
  const call = createGitTransport(app);
  const fromView = await call<RepoState>({ action: 'open', path: repository });
  assert.equal(fromView.repo, opened.state.repo);
  const state = await call<RepoState>({ action: 'stage', repo: fromView.repo, version: fromView.version, paths: ['hello.txt'], unstage: false });
  await call<RepoState>({ action: 'commit', repo: state.repo, version: state.version, message: 'MCP integration verified' });
  assert.equal((await git(repository, ['log', '-1', '--format=%s'])).trim(), 'MCP integration verified');
  // The Codex-facing hunk indices must identify precisely the reviewed patch.
  const lines = Array.from({ length: 30 }, (_, index) => `line ${index + 1}`);
  await writeFile(path.join(repository, 'notes.txt'), lines.join('\n') + '\n');
  await git(repository, ['add', 'notes.txt']);
  await git(repository, ['commit', '-m', 'baseline for partial review']);
  const modified = lines.map((line, index) => index === 1 || index === 27 ? `${line} changed` : line);
  await writeFile(path.join(repository, 'notes.txt'), modified.join('\n') + '\n');
  const reviewed = await client.callTool({ name: 'git_workbench_diff', arguments: { repo: state.repo, path: 'notes.txt' } });
  assert.ok(!reviewed.isError, JSON.stringify(reviewed));
  const diff = JSON.parse((reviewed.content as { text: string }[])[0].text);
  assert.equal(diff.comparison, 'Index → Working tree');
  assert.deepEqual(diff.hunks.map((hunk: { index: number }) => hunk.index), [0, 1]);
  assert.equal(diff.absolutePath, path.join(repository, 'notes.txt'));
  const partial = await client.callTool({ name: 'git_workbench_hunk', arguments: { repo: state.repo, version: diff.version, path: 'notes.txt', index: 0 } });
  assert.ok(!partial.isError, JSON.stringify(partial));
  const stale = await client.callTool({ name: 'git_workbench_hunk', arguments: { repo: state.repo, version: diff.version, path: 'notes.txt', index: 1 } });
  assert.equal(stale.isError, true);
  await assert.rejects(call<RepoState>({ action: 'hunk', repo: state.repo, version: diff.version, path: 'notes.txt', index: 1, unstage: false }), /./, 'UI transport must propagate stale write errors');
  const viewDiff = await call<DiffResult>({ action: 'diff', repo: state.repo, path: 'notes.txt', staged: true });
  assert.match(viewDiff.patch, /line 2 changed/);
  assert.doesNotMatch(viewDiff.patch, /line 28 changed/);
  const index = await git(repository, ['show', ':notes.txt']);
  assert.match(index, /line 2 changed/); assert.doesNotMatch(index, /line 28 changed/);
  // Selecting a chat worktree must preserve its root, branch and index.
  const worktree = path.join(root, 'worktree');
  const worktrees = await call<WorktreeState>({ action: 'worktrees', repo: state.repo });
  const added = await call<WorktreeState>({ action: 'worktreeAdd', repo: state.repo, version: worktrees.version, path: worktree, branch: 'codex-chat', newBranch: true });
  assert.equal(added.entries.length, 2);
  assert.equal(tools.tools.find(tool => tool.name === 'git_workbench_worktreeRemove')?.annotations?.destructiveHint, true);
  const worktreeResult = await client.callTool({ name: 'git_workbench_open', arguments: { path: worktree } });
  assert.ok(!worktreeResult.isError, JSON.stringify(worktreeResult));
  const worktreeState = JSON.parse((worktreeResult.content as { text: string }[])[0].text).state as RepoState;
  assert.equal(worktreeState.branch, 'codex-chat');
  assert.notEqual(worktreeState.repo, state.repo);
  assert.equal(worktreeState.files.length, 0);
  assert.equal(path.resolve(worktreeState.root), path.resolve(worktree));
  const worktreePanel = await client.callTool({ name: 'git_workbench_panel', arguments: { path: worktree } });
  assert.equal((worktreePanel.structuredContent as unknown as PanelData).roots[0]?.path, worktree);
  const anotherPanel = await client.callTool({ name: 'git_workbench_panel', arguments: {} });
  assert.equal((anotherPanel.structuredContent as unknown as PanelData).roots[0]?.path, repository, 'Empty calls use the current roots, never the last explicitly opened worktree');
  const workspace = await client.callTool({ name: 'git_workbench_workspace', arguments: { path: root } });
  assert.deepEqual((workspace.structuredContent as unknown as PanelData).repositories.map(repo => repo.repo).sort(), [opened.state.repo, worktreeState.repo].sort());
  const removed = await call<WorktreeState>({ action: 'worktreeRemove', repo: state.repo, version: added.version, path: worktree });
  assert.equal(removed.entries.length, 1);
  assert.match(await git(repository, ['show-ref', '--verify', 'refs/heads/codex-chat']), /refs\/heads\/codex-chat/);
});
