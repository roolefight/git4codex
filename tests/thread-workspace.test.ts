import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { GitService, git } from '../src/core/git';
import { listCodexProjects, resolveThreadWorkspace } from '../src/codex/workspace';
import { registerPanel } from '../src/mcp-panel';
import type { PanelData } from '../src/codex/protocol';

test('native thread metadata auto-loads the exact project and worktree without roots or path input', async t => {
  const base = path.resolve('.test-repos'); await mkdir(base, { recursive: true });
  const root = await mkdtemp(path.join(base, 'thread-workspace-'));
  const home = path.join(root, 'codex-home'); await mkdir(home);
  const project = path.join(root, 'project');
  const frontend = path.join(project, 'frontend');
  const backend = path.join(project, 'backend');
  for (const directory of [frontend, backend]) { await mkdir(directory, { recursive: true }); await git(directory, ['init', '-b', 'main']); }
  await git(frontend, ['config', 'user.name', 'Thread Test']);
  await git(frontend, ['config', 'user.email', 'thread@example.invalid']);
  await writeFile(path.join(frontend, 'README.md'), 'baseline\n');
  await git(frontend, ['add', '.']); await git(frontend, ['commit', '-m', 'baseline']);
  const worktree = path.join(root, 'task-worktree');
  await git(frontend, ['worktree', 'add', '-b', 'task', worktree]);
  const a = '11111111-1111-4111-8111-111111111111';
  const b = '22222222-2222-4222-8222-222222222222';
  const db = new DatabaseSync(path.join(home, 'state_5.sqlite'));
  // Only the two required columns exist: reading chat content would fail this test.
  db.exec('CREATE TABLE threads (id TEXT PRIMARY KEY, cwd TEXT NOT NULL)');
  db.prepare('INSERT INTO threads VALUES (?, ?)').run(a, process.platform === 'win32' ? `\\\\?\\${project}` : project);
  db.prepare('INSERT INTO threads VALUES (?, ?)').run(b, worktree);
  const service = new GitService();
  const server = new McpServer({ name: 'thread-test', version: '1' });
  registerPanel(server, directory => service.open(directory), '<title>test</title>', meta => resolveThreadWorkspace(meta, home));
  const client = new Client({ name: 'native-thread-entrypoint', version: '1' });
  const [host, transport] = InMemoryTransport.createLinkedPair();
  await server.connect(transport); await client.connect(host);
  t.after(async () => { await client.close(); await server.close(); db.close(); if (!root.startsWith(base + path.sep)) throw new Error('Unsafe cleanup'); await rm(root, { recursive: true, force: true }); });
  const read = async (id?: string) => (await client.callTool({ name: 'git_workbench_workspace', arguments: {}, ...(id ? { _meta: { thread_id: id, threadId: id } } : {}) })).structuredContent as unknown as PanelData;
  const [first, second] = await Promise.all([read(a), read(b)]);
  assert.equal(first.source, 'codex-thread'); assert.equal(first.error, undefined);
  assert.deepEqual(first.repositories.map(repo => repo.root).sort(), [frontend, backend].sort());
  assert.equal(second.repositories.length, 1); assert.equal(second.state?.root, worktree); assert.equal(second.state.branch, 'task');
  assert.equal((await read()).source, 'unavailable', 'Never reuse the last thread or process cwd');
  db.prepare('UPDATE threads SET cwd = ? WHERE id = ?').run(worktree, a);
  assert.equal((await read(a)).state?.root, worktree, 'Read fresh thread cwd after a worktree handoff');
  const missing = await read('33333333-3333-4333-8333-333333333333');
  assert.equal(missing.repositories.length, 0); assert.equal(missing.error, undefined); assert.equal(missing.source, 'unavailable', 'Ephemeral unsent chats must not guess a project or falsely report a broken database');
  await writeFile(path.join(home, '.codex-global-state.json'), JSON.stringify({ 'local-projects': { p: { id: 'p', name: 'Project', rootPaths: [project, worktree] }, invalid: { id: 'bad', name: 'Bad', rootPaths: ['relative'] } }, 'selected-project': { id: 'unrelated' } }));
  assert.deepEqual(await listCodexProjects(home), [{ id: 'p', name: 'Project', paths: [project, worktree] }]);
  await assert.rejects(resolveThreadWorkspace({ thread_id: a, threadId: b }, home), /不一致/);
  const explicit = (await client.callTool({ name: 'git_workbench_workspace', arguments: { path: backend }, _meta: { thread_id: a } })).structuredContent as unknown as PanelData;
  assert.equal(explicit.state?.root, backend, 'An explicitly added project takes precedence');
  assert.equal((await resolveThreadWorkspace({ threadId: b }, home)), worktree);
  await assert.rejects(resolveThreadWorkspace({ thread_id: '../unexpected' }, home), /无效/);
  assert.equal(await resolveThreadWorkspace(undefined, path.join(root, 'absent-home')), undefined);
});
