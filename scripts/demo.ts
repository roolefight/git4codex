import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { git } from '../src/core/git';
const root = path.resolve('.test-repos', `demo-${Date.now()}`);
await mkdir(root, { recursive: true });
await git(root, ['init', '-b', 'main']);
await git(root, ['config', 'user.name', 'Workbench Demo']);
await git(root, ['config', 'user.email', 'demo@example.invalid']);
await git(root, ['config', 'core.autocrlf', 'false']);
await mkdir(path.join(root, 'src'), { recursive: true });
await writeFile(path.join(root, 'src', 'repository.ts'), 'export function repositoryLabel(name: string) {\n  return name;\n}\n\nexport const refreshInterval = 10000;\n');
await writeFile(path.join(root, 'README.md'), '# Git Workbench 测试仓库\n\n仅用于验证插件操作。\n');
await git(root, ['add', '.']); await git(root, ['commit', '-m', '初始化仓库视图']);
await git(root, ['switch', '-c', 'feature/repository-status']);
await writeFile(path.join(root, 'src', 'status.ts'), 'export const statusLabels = {\n  modified: "已修改",\n  staged: "已暂存",\n};\n');
await git(root, ['add', '.']); await git(root, ['commit', '-m', '增加仓库状态标签']);
await writeFile(path.join(root, 'src', 'repository.ts'), 'export function repositoryLabel(name: string) {\n  const normalized = name.trim();\n  return normalized || "未命名仓库";\n}\n\nexport const refreshInterval = 3000;\n');
await writeFile(path.join(root, 'README.md'), '# Git Workbench 测试仓库\n\n仅用于验证插件操作。\n\n支持按代码块暂存与双栏差异对比。\n');
await git(root, ['add', 'README.md']);
await writeFile(path.join(root, 'src', 'branch.ts'), 'export const defaultBranch = "main";\n');
await writeFile('.runtime/demo-path.txt', root).catch(async () => { await mkdir('.runtime', { recursive: true }); await writeFile('.runtime/demo-path.txt', root); });
console.log(root);
